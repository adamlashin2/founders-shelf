"""Import the Notensprung design system into The Greats.

The Greats' design system is Notensprung's (Adam, 2026-11-08: "take the design system from my Notensprung… use it as the
authoritative"). Nothing here is chosen by eye: every value is read from Notensprung itself —
  D:/Notensprung/app/src/design/invite.tokens.json   (measured from the founding invite screen by tools/measure_invite.py)
  D:/Notensprung/app/src/index.css                    (the --ns-* theme variables, dark + light)
and written into app/index.html between the NS-TOKENS markers. Re-run after Notensprung re-measures.
Run from the repo root:  python tools/ns_tokens.py
"""
import json, re
from pathlib import Path

NS = Path('D:/Notensprung/app/src')
ROOT = Path(__file__).resolve().parent.parent
HTML = ROOT / 'app' / 'index.html'
T = json.loads((NS / 'design' / 'invite.tokens.json').read_text(encoding='utf-8'))
css = (NS / 'index.css').read_text(encoding='utf-8')


def block(selector):
    """the declarations of the first rule whose selector is exactly `selector` and that defines --ns-* vars"""
    for m in re.finditer(re.escape(selector) + r'\s*\{([^}]*)\}', css):
        body = m.group(1)
        if '--ns-' in body:
            return {k: v.strip() for k, v in re.findall(r'(--ns-[\w-]+)\s*:\s*([^;]+);', body)}
    raise SystemExit(f'no --ns block for {selector}')


dark = {}
for m in re.finditer(r':root\s*\{([^}]*)\}', css):
    dark.update({k: v.strip() for k, v in re.findall(r'(--ns-[\w-]+)\s*:\s*([^;]+);', m.group(1)) if '--ns-' in m.group(1)})
light = block(':root[data-theme="light"]')
force_dark = block('.ns-force-dark')   # the founding reference stays dark in both themes: photo screens use it

seg, card, cap, btn, ty = T['segmented'], T['card'], T['capsule'], T['roundButton'], T['type']
inset = round(seg['pill']['y'] - seg['y'], 2)
measured = {
    # shapes
    '--ns-btn-d': f"{btn['left']['d']}px", '--ns-btn-cx': f"{btn['left']['cx']}px", '--ns-btn-cy': f"{btn['left']['cy']}px",
    '--ns-seg-w': f"{seg['w']}px", '--ns-seg-h': f"{seg['h']}px", '--ns-seg-inset': f"{inset}px",
    '--ns-pill-h': f"{seg['pill']['h']}px", '--ns-pill-w': f"{seg['pill']['w']}px", '--ns-pill-fill': seg['pill']['fill'],
    '--ns-on': seg['labelOn'], '--ns-disc-on': seg['glyphDiscOn'], '--ns-divider': seg['divider']['color'],
    '--ns-card-r': f"{card['radius']}px", '--ns-card-x': f"{card['x']}px", '--ns-card-pad-top': f"{round(card['avatar']['y'] - card['y'], 2)}px",
    '--ns-avatar-d': f"{card['avatar']['d']}px", '--ns-cap-h': f"{cap['h']}px",
    '--ns-nav-bottom': f"{round(852 - (cap['y'] + cap['h']), 2)}px",
    # rhythm (gaps between consecutive elements of the reference)
    '--ns-gap-title-info': f"{round(T['info']['box']['y'] - (T['title']['box']['y'] + T['title']['box']['h']), 2)}px",
    '--ns-gap-info-seg': f"{round(seg['y'] - (T['info']['box']['y'] + T['info']['box']['h']), 2)}px",
    '--ns-gap-seg-card': f"{round(card['y'] - (seg['y'] + seg['h']), 2)}px",
    '--ns-gap-avatar-host': f"{round(card['host']['box']['y'] - (card['avatar']['y'] + card['avatar']['d']), 2)}px",
    '--ns-gap-host-body': f"{round(card['p1']['box']['y'] - (card['host']['box']['y'] + card['host']['box']['h']), 2)}px",
    # ink alpha for info lines
    '--ns-info-a': str(T['info']['whiteAlpha']),
}
for k, t in ty.items():
    measured[f'--ns-{k}-size'] = f"{t['size']}px"; measured[f'--ns-{k}-weight'] = str(t['weight']); measured[f'--ns-{k}-track'] = f"{t['tracking']}px"
    if 'leading' in t: measured[f'--ns-{k}-lead'] = f"{t['leading']}px"
measured['--ns-segment-weight-on'] = str(ty['segment']['weightOn'])

fmt = lambda d: ''.join(f'{k}:{v};' for k, v in d.items())
out = ('/* NS-TOKENS:BEGIN — generated by tools/ns_tokens.py from D:/Notensprung (invite.tokens.json + index.css). Do not edit by hand. */\n'
       f':root{{{fmt(measured)}{fmt(dark)}}}\n'
       f'html.light{{{fmt(light)}}}\n'
       f'html.light .home-x,html.light .fx,html.light #np,html.light body.on-photo #nshdr,html.light body.on-figure #nshdr{{{fmt(force_dark)}}}\n'
       '/* NS-TOKENS:END */')
s = HTML.read_text(encoding='utf-8')
if '/* NS-TOKENS:BEGIN' in s:
    s = re.sub(r'/\* NS-TOKENS:BEGIN.*?/\* NS-TOKENS:END \*/', lambda m: out, s, flags=re.S)
else:
    s = s.replace('</style>', out + '\n</style>', 1)
HTML.write_text(s, encoding='utf-8')
print(f'{len(measured)} measured + {len(dark)} dark + {len(light)} light variables written')
